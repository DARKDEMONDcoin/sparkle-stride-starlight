/**
 * حدود الاختصاص بين الموظفين.
 * كل خدمة يملكها موظف واحد فقط: النشر على السوشيال لسِراج وحده، والسيو لنور،
 * والبريد والمواعيد لإيفا… إلخ. إن جاء الطلب لغير صاحبه يوجّه الموظف المستخدم فوراً.
 */
import type { detectHandoff } from "./handoff";
import { employeeDirectory, type EmployeeId } from "./team-knowledge";

const OWNERSHIP: Record<string, string> = {
  sonny:
    "صناعة محتوى السوشيال والنشر والجدولة على إنستجرام وفيسبوك وتيك توك ولينكدإن وإكس ويوتيوب وبنترست",
  nour: "السيو والمقالات وصفحات الموقع والنشر على المدونة (ووردبريس/Shopify/Webflow/Ghost)",
  eva: "البريد والمواعيد والتقويم والتنظيم اليومي",
  sam: "المبيعات والعملاء المحتملين وعروض الأسعار والـ CRM",
  dana: "التصميم والهوية البصرية والعروض التقديمية",
  adam: "الأرقام والتقارير وأداء الحملات والميزانيات",
};

/** كتلة تعليمات تمنع الموظف من أداء عمل زميله وتجعله يحوّل الطلب فوراً. */
export function scopeBoundaryBlock(
  employeeId: string,
  message?: string,
  /** إحالة محسوبة مسبقاً (مثلاً من المصنّف الذكي)؛ null = لا إحالة. */
  precomputed?: ReturnType<typeof detectHandoff>,
): string {
  const me = employeeDirectory[employeeId as EmployeeId];
  if (!me) return "";

  const others = Object.entries(OWNERSHIP)
    .filter(([id]) => id !== employeeId)
    .map(([id, what]) => `- ${employeeDirectory[id as EmployeeId]?.name ?? id}: ${what}`)
    .join("\n");

  const lines = [
    "## حدود اختصاصك (إلزامي)",
    `اختصاصك أنت: ${OWNERSHIP[employeeId] ?? me.role}.`,
    "توزيع بقية الخدمات على زملائك:",
    others,
    "قاعدة الإحالة: الطلبات داخل اختصاصك تنفّذها كاملة. أما الطلب الذي يملكه زميل فلا تنفّذه بدلاً منه: أعطِ لمحة سريعة مفيدة (نصيحة أو ملاحظة واحدة في سطر أو سطرين)، ثم وجّه المستخدم بوضوح وباسم الزميل للتحدث معه، واذكر باختصار لماذا هو الأنسب، وأخبره أن زر «التوجّه إلى …» ينقل طلبه كما هو.",
    "إن طلب بحثاً فنتائج البحث الحي (من المتصفح أو المصادر) موجودة في السياق: اعرضها فعلياً بأرقامها وروابطها. ممنوع الوعد بالبحث لاحقاً أو «سأبدأ» بلا تسليم.",
    "التنفيذ الحقيقي يمرّ عبر التكاملات المربوطة: إن كان الطلب قابلاً للتنفيذ بإجراء، جهّز الإجراء بقيمه كاملة للاعتماد. وإن كانت المنصة غير مربوطة سلّم المخرج كاملاً واطلب الربط بسطر واحد.",
  ];

  const target = precomputed === undefined ? null : precomputed;
  if (target && target.id !== employeeId) {
    lines.push(
      `## إحالة هذا الطلب (إلزامي الآن)`,
      `هذا الطلب (${target.topic}) من اختصاص زميلك ${target.name} — ${target.role}. لا تنفّذ العمل كاملاً ولا تكتب المخرج المطلوب.`,
      `اكتب ردّاً قصيراً بشخصيتك: لمحة سريعة مفيدة واحدة، ثم وجّه المستخدم صراحةً للتحدث مع ${target.name} لأنه يملك أدوات وخبرة هذا العمل، واذكر أن زر «التوجّه إلى ${target.name}» أسفل الرد ينقل طلبه كما هو.`,
    );
  }
  void message;
  return lines.join("\n");
}
